import {existsSync} from 'node:fs'
import fs from 'node:fs/promises'
import path from 'node:path'

const SCENARIOS_DIR = path.resolve(import.meta.dirname, '../../../scenarios')
const SRC_DIR = path.resolve(import.meta.dirname, '../src')

const scenarios = await fs.readdir(SCENARIOS_DIR).then(async filenames => {
  const results = []

  for (const filename of filenames) {
    const directory = path.join(SCENARIOS_DIR, filename)
    const stats = await fs.stat(directory)
    if (!stats.isDirectory()) {
      continue
    }

    const configPath = path.join(directory, 'scenario.config.ts')
    if (!existsSync(configPath)) {
      throw new Error(`No scenario.config.ts found in ${path.basename(directory)}`)
    }

    const configModule = await import(configPath)

    const testPath = path.join(directory, 'scenario.test.ts')
    if (!existsSync(testPath)) {
      throw new Error(`No scenario.test.ts found in ${path.basename(directory)}`)
    }

    results.push({
      id: filename,
      directory,
      config: configModule.default,
      testPath,
    })
  }

  return results
})

const GENERATED_FOLDER = path.join(SRC_DIR, 'generated')
await fs.mkdir(GENERATED_FOLDER, {recursive: true})

const GENERATED_FILEPATH = path.join(GENERATED_FOLDER, 'scenarios.ts')
const contents = `// This file is auto-generated by script/build-scenarios.ts. Do not edit this file directly.

const data = ${JSON.stringify(scenarios, null, 2)} as const

type ScenarioId = typeof data[number]['id']
type Scenario = typeof data[number];

export { data }
export type { ScenarioId, Scenario }
`

await fs.writeFile(GENERATED_FILEPATH, contents)
