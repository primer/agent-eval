import {existsSync} from 'node:fs'
import fs from 'node:fs/promises'
import path from 'node:path'

const EVALS_DIR = path.resolve(import.meta.dirname, '../../../evals')
const SRC_DIR = path.resolve(import.meta.dirname, '../src')

const evals = await fs.readdir(EVALS_DIR).then(async filenames => {
  const results = []

  for (const filename of filenames) {
    const directory = path.join(EVALS_DIR, filename)
    const stats = await fs.stat(directory)
    if (!stats.isDirectory()) {
      continue
    }

    const configPath = path.join(directory, 'eval.config.ts')
    if (!existsSync(configPath)) {
      throw new Error(`No eval.config.ts found in ${path.basename(directory)}`)
    }

    const configModule = await import(configPath)
    const config = configModule.default
    const testFiles = normalizeTestFiles(config.testFiles)

    const testPaths = testFiles.map(testFile => path.join(directory, testFile))
    for (const [index, testPath] of testPaths.entries()) {
      if (!existsSync(testPath)) {
        throw new Error(`No test file "${testFiles[index]}" found in ${path.basename(directory)}`)
      }
    }

    results.push({
      id: filename,
      directory,
      config,
      testFiles,
      testPaths,
    })
  }

  return results
})

const GENERATED_FOLDER = path.join(SRC_DIR, 'generated')
await fs.mkdir(GENERATED_FOLDER, {recursive: true})

const GENERATED_FILEPATH = path.join(GENERATED_FOLDER, 'evals.ts')
const contents = `// This file is auto-generated by script/build-evals.ts. Do not edit this file directly.

const data = ${JSON.stringify(evals, null, 2)} as const

type EvalId = typeof data[number]['id']
type Eval = typeof data[number];

export { data }
export type { EvalId, Eval }
`

await fs.writeFile(GENERATED_FILEPATH, contents)

function normalizeTestFiles(testFiles: unknown): Array<string> {
  if (
    !Array.isArray(testFiles) ||
    testFiles.length === 0 ||
    !testFiles.every(testFile => typeof testFile === 'string')
  ) {
    throw new Error('Eval config testFiles must be a non-empty array of file paths')
  }

  const normalizedTestFiles = testFiles.map(testFile => {
    const normalized = path.posix.normalize(testFile.split(path.sep).join(path.posix.sep))
    if (normalized === '.' || normalized.startsWith('../') || path.posix.isAbsolute(normalized)) {
      throw new Error(`Eval config testFiles must stay within the eval directory: "${testFile}"`)
    }
    return normalized
  })

  if (new Set(normalizedTestFiles).size !== normalizedTestFiles.length) {
    throw new Error('Eval config testFiles must not contain duplicates')
  }

  return normalizedTestFiles
}
